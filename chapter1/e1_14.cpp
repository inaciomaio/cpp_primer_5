// while loops are simple and straight forward
// for loops are also simple, but the variable defined and its incrementation are defined inside it

// E.G
// here we define everything in a single line:
// for(i = 0; i < 10; i++) {
//  do something;  
// }

// whilest in a while loop it would be something along the lines of:
// int i = 0;
// while(i < 10) {
//  do something;
//  i++;
// }

// for loops are nice because the variable is scoped and doesn't require manually incrementing the value